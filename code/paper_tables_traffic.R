# Traffic truth table, read from the paper_selection caches (no reruns).
# Run from code/:  Rscript paper_tables_traffic.R
#
# 1. Load cached results for seven candidates at the 10% and 20% sampling budgets.
# 2. Get domain truths and traffic shares from the single-sample cache.
# 3. Summarize traffic-weighted RMSE, interval score, and coverage across replications.
#    RMSE uses cached oracle errors; interval score and coverage use cached bounds.
# 4. Format and write the traffic truth table.
# Output: ../paper/tables/traffic_truth.tex (tab:traffic-truth-app).

# ---- 1. Load cached results for seven candidates at the 10% and 20% sampling budgets. ----
library(dplyr)
dir.create("../paper/tables", showWarnings = FALSE)
rd <- function(f) readRDS(file.path("../data", f))
ss <- rd("paper_single_sample_10.rds")
psel <- lapply(c("10", "20"), function(p) rd(sprintf("paper_selection_%s.rds", p)))
names(psel) <- c("10", "20")

TAG <- c(direct = "HT", greg_judge = "GREG (judge)",
         greg_full = "GREG (judge + content)", pps_judge = "PP-S (judge)",
         pps_full = "PP-S (judge + content)", ppts_judge = "PP-TS (judge)",
         ppts_full = "PP-TS (judge + content)")

# ---- 2. Get domain truths and traffic shares from the single-sample cache. ----
cn <- rownames(psel[["10"]]$done[[1]]$lo)
domain_truth <- data.frame(domain = cn) |>
  left_join(dplyr::select(ss$est, domain, truth, N), by = "domain") |>
  mutate(weight = N / sum(N))
tr <- domain_truth$truth
qw <- domain_truth$weight

# ---- 3. Summarize traffic-weighted RMSE, interval score, and coverage across replications. ----
metrics <- function(o, alpha = 0.05) {
  iv <- lapply(o$done, function(d) {
    isx <- (d$hi - d$lo) + (2 / alpha) * pmax(d$lo - tr, 0) +
      (2 / alpha) * pmax(tr - d$hi, 0)
    rbind(IS = colSums(qw * isx),
          cov = colSums(qw * (tr >= d$lo & tr <= d$hi)))
  })
  m <- Reduce(`+`, iv) / length(iv)
  rbind(rmse = sqrt(colMeans(t(sapply(o$done, `[[`, "oracle")))), m)[, names(TAG)]
}

# ---- 4. Format and write the traffic truth table. ----
# Bold the lowest RMSE/interval score and the coverage closest to 95%.
bold <- function(txt, i) { txt[i] <- paste0("\\textbf{", txt[i], "}"); txt }
fmt <- function(v, d) formatC(v, format = "f", digits = d)
cols <- function(p) {
  m <- metrics(psel[[p]])
  paste0(bold(fmt(m["rmse", ], 3), which.min(m["rmse", ])), " & ",
         bold(fmt(m["IS", ], 2), which.min(m["IS", ])), " & ",
         bold(fmt(m["cov", ], 3), which.min(abs(m["cov", ] - 0.95))))
}
body <- paste0(TAG, " & ", cols("10"), " & ", cols("20"), " \\\\")

writeLines(c(
  "% Generated by code/paper_tables_traffic.R -- do not edit by hand.",
  "\\begin{table}[H]", "\\centering", "\\small", "\\setlength{\\tabcolsep}{4pt}",
  "\\caption{The candidate field against the oracle at both budgets, weighted by traffic share over 100 replications: RMSE, the interval score, and the empirical coverage of the nominal 95\\% intervals. HT is the Horvitz--Thompson estimator. The best RMSE, the best interval score, and the coverage closest to nominal in each budget are bold.}",
  "\\label{tab:traffic-truth-app}",
  "\\begin{tabular}{lrrrrrr}", "\\toprule",
  " & \\multicolumn{3}{c}{10\\%} & \\multicolumn{3}{c}{20\\%} \\\\",
  "\\cmidrule(lr){2-4} \\cmidrule(lr){5-7}",
  "candidate & RMSE & IS & coverage & RMSE & IS & coverage \\\\",
  "\\midrule", body, "\\bottomrule", "\\end{tabular}", "\\end{table}"),
  "../paper/tables/traffic_truth.tex")
cat("wrote paper/tables/traffic_truth.tex\n")
