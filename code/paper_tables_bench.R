# Benchmark simulation tables from cached paper_smoothing results (no reruns).
# 1. Load cached results for three auxiliaries at the 10%, 20%, and 30% budgets.
# 2. Average metrics across replications and format the table columns.
# 3. Write the RMSE, interval-score, and coverage tables for all estimators.
# 4. Write the seven-estimator table at 10% and print standard errors.
# Run from code/: Rscript paper_tables_bench.R
#
# All files go in ../paper/tables/; bench_main.tex contains only the tabular body.

library(dplyr)
source("R/run.R")
dir.create("../paper/tables", showWarnings = FALSE)
# ---- 1. Load cached results for three auxiliaries at the 10%, 20%, and 30% budgets. ----

ARMS <- c("math", "weak", "strong")   # cache tag
AUX_LAB <- c(math = "Specialist model", weak = "Generalist model",
             strong = "Historical difficulty")  # column headers
FRAC <- c("10", "20", "30")

RUNGS <- c(
  "$\\hat{\\theta}_i^{\\mathrm{HT}}$"                      = "direct",
  "$\\hat{\\theta}_i^{\\mathrm{PPI}}$"                                = "ppi",
  "$\\hat{\\theta}_i^{\\mathrm{GREG}}$"                               = "ppi_tuned",
  "$\\hat{\\theta}_i^{\\mathrm{FH}}$, intercept"                      = "fh_intercept",
  "$\\hat{\\theta}_i^{\\mathrm{FH}}$, covariate"                      = "fh_judge",
  "$\\hat{\\theta}_i^{\\mathrm{PP\\text{-}S}}$, intercept"            = "pp_s_intercept",
  "$\\hat{\\theta}_i^{\\mathrm{PP\\text{-}S}}$, covariate"            = "pp_s_judge",
  "$\\hat{\\theta}_i^{\\mathrm{TFH}}$, intercept"                     = "ts_intercept",
  "$\\hat{\\theta}_i^{\\mathrm{TFH}}$, covariate"                     = "ts_judge",
  "$\\hat{\\theta}_i^{\\mathrm{PP\\text{-}TS}}$, intercept"           = "ts_greg_intercept",
  "$\\hat{\\theta}_i^{\\mathrm{PP\\text{-}TS}}$, covariate"           = "ts_greg_judge")
BLOCK_END <- c(3, 7)  # rules after the direct and flat blocks

sm <- list()
for (a in ARMS) for (p in FRAC)
  sm[[paste(a, p)]] <- readRDS(sprintf("../data/paper_smoothing_%s_%s.rds", p, a))

# ---- 2. Average metrics across replications and format the table columns. ----
grab <- function(key, metric) {
  means <- sm[[key]]$metrics |>
    filter(.data$metric == .env$metric) |>
    group_by(estimator) |>
    summarise(value = mean(value), .groups = "drop") |>
    pull(value, name = estimator)
  means[RUNGS]
}

ladder <- function(metric, digits, file, label, caption, best = c("min", "nominal")) {
  best <- match.arg(best)
  keys <- as.vector(t(outer(ARMS, FRAC, paste)))
  M <- sapply(keys, function(k) grab(k, metric))
  txt <- matrix(formatC(M, format = "f", digits = digits), nrow(M))
  for (j in seq_len(ncol(M))) {
    i <- if (best == "min") which.min(M[, j]) else which.min(abs(M[, j] - 0.95))
    txt[i, j] <- paste0("\\textbf{", txt[i, j], "}")
  }
  body <- paste0(names(RUNGS), " & ", apply(txt, 1, paste, collapse = " & "), " \\\\")
  body[BLOCK_END] <- paste0(body[BLOCK_END], "\n\\midrule")
  writeLines(c(
    "% Generated by code/paper_tables_bench.R -- do not edit by hand.",
    "\\begin{table}[h]", "\\centering", "\\small", "\\setlength{\\tabcolsep}{4pt}",
    paste0("\\caption{", caption, "}"), paste0("\\label{", label, "}"),
    paste0("\\begin{tabular}{l", paste(rep("c", ncol(M)), collapse = ""), "}"),
    "\\toprule",
    paste0("& ", paste(sprintf("\\multicolumn{3}{c}{%s}", AUX_LAB[ARMS]),
                       collapse = " & "), " \\\\"),
    paste(sprintf("\\cmidrule(lr){%d-%d}", seq(2, 8, 3), seq(4, 10, 3)), collapse = " "),
    paste0("Estimator & ", paste(rep(paste0(FRAC, "\\%"), 3), collapse = " & "), " \\\\"),
    "\\midrule", body, "\\bottomrule", "\\end{tabular}", "\\end{table}"), file)
}

# ---- 3. Write the RMSE, interval-score, and coverage tables for all estimators. ----
ladder("rmse", 4, "../paper/tables/bench_rmse.tex", "tab:bench-rmse",
  "RMSE over the 34 domains, averaged over 100 replications, at each sampling budget and under each auxiliary. Lower is better and the best value in each column is bold.")
ladder("IS", 4, "../paper/tables/bench_is.tex", "tab:bench-is",
  "Interval score of the nominal 95\\% intervals, averaged over 100 replications, at each sampling budget and under each auxiliary. Lower is better and the best value in each column is bold.")
ladder("coverage", 3, "../paper/tables/bench_coverage.tex", "tab:bench-coverage",
  "Empirical coverage of the nominal 95\\% intervals, averaged over 100 replications, at each sampling budget and under each auxiliary. The value closest to nominal in each column is bold.", best = "nominal")

# ---- 4. Write the seven-estimator table at 10% and print standard errors. ----
# Same caches as above; the smoothers are the covariate-carrying versions.
MAIN_ARMS <- c("math", "weak", "strong")
MAIN_LAB <- c(math = "Specialist model", weak = "Generalist model",
              strong = "Historical difficulty")
MAIN_RUNGS <- RUNGS[c(1, 2, 3, 5, 7, 9, 11)]
names(MAIN_RUNGS) <- c("$\\hat{\\theta}_i^{\\mathrm{HT}}$", "$\\hat{\\theta}_i^{\\mathrm{PPI}}$",
  "$\\hat{\\theta}_i^{\\mathrm{GREG}}$", "$\\hat{\\theta}_i^{\\mathrm{FH}}$",
  "$\\hat{\\theta}_i^{\\mathrm{PP\\text{-}S}}$", "$\\hat{\\theta}_i^{\\mathrm{TFH}}$",
  "$\\hat{\\theta}_i^{\\mathrm{PP\\text{-}TS}}$")
main_summary <- function(a, metric) {
  summary <- sm[[paste(a, "10")]]$metrics |>
    filter(.data$metric == .env$metric) |>
    group_by(estimator) |>
    summarise(
      mu = mean(value),
      se = sd(value) / sqrt(n()),
      .groups = "drop"
    )
  list(mu = setNames(summary$mu, summary$estimator)[MAIN_RUNGS],
       se = setNames(summary$se, summary$estimator)[MAIN_RUNGS])
}
MC <- lapply(MAIN_ARMS, function(a) list(rmse = main_summary(a, "rmse"), IS = main_summary(a, "IS")))
M  <- do.call(cbind, lapply(MC, function(x) cbind(x$rmse$mu, x$IS$mu)))
SE <- do.call(cbind, lapply(MC, function(x) cbind(x$rmse$se, x$IS$se)))
dimnames(M) <- dimnames(SE) <- list(MAIN_RUNGS, paste(rep(MAIN_ARMS, each = 2), c("rmse", "IS")))
txt <- matrix("", nrow(M), ncol(M))
for (j in seq_len(ncol(M))) {
  txt[, j] <- formatC(M[, j], format = "f", digits = if (max(M[, j]) < 1) 3 else 2)
  i <- which.min(M[, j]); txt[i, j] <- paste0("\\textbf{", txt[i, j], "}")
}
body <- paste0(names(MAIN_RUNGS), " & ", apply(txt, 1, paste, collapse = " & "), " \\\\")
body[c(3, 5)] <- paste0(body[c(3, 5)], "\n\\midrule")
se_r <- formatC(max(SE[, c(1, 3, 5)]), format = "g", digits = 1)
se_i <- formatC(max(SE[, c(2, 4, 6)]), format = "g", digits = 1)
# Tabular only: the table environment, caption and label are in the paper source.
# The largest standard errors, quoted in the caption, are printed below.
writeLines(c(
  "% Generated by code/paper_tables_bench.R -- do not edit by hand.",
  "% Tabular only; the table environment, caption and label are in the paper source.",
  "\\begin{tabular}{lcccccc}", "\\toprule",
  paste0("& ", paste(sprintf("\\multicolumn{2}{c}{%s}", MAIN_LAB[MAIN_ARMS]), collapse = " & "), " \\\\"),
  "\\cmidrule(lr){2-3} \\cmidrule(lr){4-5} \\cmidrule(lr){6-7}",
  "Estimator & RMSE & IS & RMSE & IS & RMSE & IS \\\\",
  "\\midrule", body, "\\bottomrule", "\\end{tabular}"),
  "../paper/tables/bench_main.tex")
cat("\nmain table means\n"); print(round(M, 4)); cat("\nstandard errors\n"); print(signif(SE, 2))
cat("\nlargest standard errors:", se_r, "for RMSE and", se_i, "for the interval score\n")

cat("wrote paper/tables/bench_{rmse,is,coverage,main}.tex\n")
